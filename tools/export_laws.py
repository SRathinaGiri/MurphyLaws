"""Export murphy.db -> laws.js for the PWA.

Run again whenever murphy.db changes; the service worker is network-first, so
installed copies pick up the new data on their next online launch.
"""
from __future__ import annotations

import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    db = ROOT / "murphy.db"
    if not db.exists():
        raise SystemExit(f"murphy.db not found at {db}")
    with sqlite3.connect(db) as con:
        rows = con.execute(
            "SELECT slno, trim(law) FROM murphy WHERE trim(coalesce(law,'')) <> '' ORDER BY slno"
        ).fetchall()
    # A .js file (not .json) so index.html also works when opened directly via file://
    payload = json.dumps([[n, t] for n, t in rows], ensure_ascii=False, separators=(",", ":"))
    out = ROOT / "laws.js"
    out.write_text(f"// Generated by tools/export_laws.py — do not edit.\nconst LAWS={payload};\n", encoding="utf-8")
    print(f"Wrote {len(rows)} laws to {out}")


if __name__ == "__main__":
    main()
